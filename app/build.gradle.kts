val keystoreProps = Properties()
rootProject.file("keystore.properties").takeIf { it.exists() }?.inputStream()?.use { keystoreProps.load(it) }

android {
    namespace = "com.example.usagetracker"
    compileSdk = 37

    defaultConfig {
        applicationId = "com.example.usagetracker"
        minSdk = 26
